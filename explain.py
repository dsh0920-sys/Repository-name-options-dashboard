def tip(key):
    """마우스를 올렸을 때 보여줄 한 덩어리 설명."""
    t = TEXT.get(key)
    if not t:
        return ""
    parts = [t["headline"], t["body"], f'↑ {t["high"]}', f'↓ {t["low"]}']
    if t.get("caveat"):
        parts.append(f'⚠ {t["caveat"]}')
    return " ".join(parts)
